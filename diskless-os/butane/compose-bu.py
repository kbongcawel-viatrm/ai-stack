#!/usr/bin/env python3
"""Compose modular Butane fragments for the FCOS guest.

Discovers Butane fragments (``*.bu``) under ``diskless-os/services/*/`` plus the
base ``diskless-os/butane/fcos.bu``, resolves ``@@include <path>@@`` markers by
inlining repository files into ``storage.files[].contents.inline`` blocks, and
writes rendered fragments plus a generated ``root.bu`` into an output directory.

Marker syntax (must be alone on its own line, inside an ``inline: |`` block):

    contents:
      inline: |
        @@include diskless-os/services/ssh/00-local-security.conf@@

The referenced file's content is inserted with each line indented to the
marker line's indentation. Paths are relative to the repository root.

The generated ``root.bu`` merges every rendered fragment through
``ignition.config.merge``; transpile each ``*.bu`` (except ``root.bu``) to
``*.ign`` first, then transpile ``root.bu`` with ``--files-dir`` pointing at
the output directory.

Usage:
    compose-bu.py --out-dir BUILD_DIR [--repo-root REPO_ROOT]
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

MARKER_RE = re.compile(r"^(?P<indent>\s*)@@include\s+(?P<path>\S+)@@\s*$")

BASE_BU = Path("diskless-os/butane/fcos.bu")
SERVICES_DIR = Path("diskless-os/services")


def render_includes(text: str, repo_root: Path, source: Path) -> str:
    """Replace @@include markers with file contents, preserving indentation."""
    out_lines: list[str] = []
    for lineno, line in enumerate(text.splitlines(), start=1):
        match = MARKER_RE.match(line)
        if not match:
            out_lines.append(line)
            continue
        rel = match.group("path")
        target = repo_root / rel
        if not target.is_file():
            raise SystemExit(f"{source}:{lineno}: include target not found: {rel}")
        indent = match.group("indent")
        body = target.read_text().splitlines()
        if body and body[-1] == "":
            body.pop()
        for body_line in body:
            out_lines.append(indent + body_line if body_line else "")
    return "\n".join(out_lines) + "\n"


def output_name(path: Path, services_dir: Path) -> str:
    """Map a fragment path to a unique flat output name.

    ``services/<svc>/<svc>.bu`` -> ``<svc>.bu``; ``butane/fcos.bu`` -> ``fcos.bu``;
    other service fragments -> ``<svc>-<stem>.bu``.
    """
    stem = path.stem
    parent = path.parent.name
    in_services = services_dir in path.parents
    if path.parent.name == "butane" or (in_services and stem == parent):
        return f"{stem}.bu"
    if in_services:
        return f"{parent}-{stem}.bu"
    return f"{stem}.bu"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out-dir", required=True, type=Path)
    parser.add_argument("--repo-root", type=Path, default=None)
    args = parser.parse_args()

    repo_root = (args.repo_root or Path(__file__).resolve().parents[2]).resolve()
    services_dir = repo_root / SERVICES_DIR
    base_bu = repo_root / BASE_BU

    fragments: list[tuple[Path, str]] = []
    if base_bu.is_file():
        fragments.append((base_bu, output_name(base_bu, services_dir)))

    if services_dir.is_dir():
        for bu in sorted(services_dir.glob("*/*.bu")):
            name = output_name(bu, services_dir)
            if any(existing == name for _, existing in fragments):
                raise SystemExit(f"duplicate fragment output name: {name}")
            fragments.append((bu, name))

    if not fragments:
        raise SystemExit("no Butane fragments found")

    args.out_dir.mkdir(parents=True, exist_ok=True)
    rendered_names: list[str] = []
    for source, name in fragments:
        text = render_includes(source.read_text(), repo_root, source)
        target = args.out_dir / name
        target.write_text(text)
        rendered_names.append(name)
        print(f"rendered {source.relative_to(repo_root)} -> {target}")

    merge_entries = "\n".join(f"      - local: {Path(n).with_suffix('.ign').name}" for n in rendered_names)
    root = (
        "variant: fcos\n"
        "version: 1.6.0\n"
        "\n"
        "# Generated by diskless-os/butane/compose-bu.py — do not edit by hand.\n"
        "# Transpile every sibling *.bu to *.ign first, then transpile this file\n"
        "# with --files-dir pointing at this directory.\n"
        "ignition:\n"
        "  config:\n"
        "    merge:\n"
        f"{merge_entries}\n"
    )
    (args.out_dir / "root.bu").write_text(root)
    print(f"wrote {args.out_dir / 'root.bu'} merging {len(rendered_names)} fragments")
    return 0


if __name__ == "__main__":
    sys.exit(main())
